# -*- coding: utf-8 -*-
r"""
영상 위에 얹는 황주 고정 문구

글꼴·크기·위치·색을 캡컷 「황주영상」 프로젝트에서 읽어 그대로 맞췄습니다.
내가 보기 좋은 값으로 새로 잡지 않습니다 (사장님 지시).

캡컷 원본 값 (캔버스 1920x1080)

    채널명      BMEULJIRO  size 13 x scale 0.379   중심(209, 55)    흰색
    안내 문구   BMEULJIRO  size 7  x scale 1.120   중심(1155, 99)   초록 #00ff18
    하단 문구   BMEULJIRO  size 9  x scale 1.000   중심(960, 959)   흰색
    인트로      BMEULJIRO  size 9  x scale 1.381   중심(960, 590)   흰색

캡컷의 글자 크기 단위는 픽셀이 아니라서, 글상자 폭(fixed_width)과 글자 수로
역산해 픽셀 크기를 맞췄습니다.
"""

import os
import shutil

글꼴 = os.path.join(os.environ.get("LOCALAPPDATA", ""),
                  "Microsoft", "Windows", "Fonts", "BMEULJIRO.otf")

가로, 세로 = 1920, 1080

채널명 = "황금주파수 TV"
안내문구 = ("댓글에 소원을 적으면 원하는 모든것이 이뤄집니다\n"
        "다른분들의 소원에도 공감, 댓글로 응원해주세요")
하단문구 = ("부처님의 자비로운 말씀이\n"
        "마음의 번뇌를 씻어주고 평안과 복을 부릅니다.")

인트로들 = [
    ("황금 주파수TV에\n오신분 모두 감사드립니다", 2.7),
    ("구독 좋아요 눌러주신 후\n소원을 댓글에 적어주시면", 2.8),
    ("모두 이루어지실거에요", 2.2),
    ("간절히 부르면 반드시\n응답하신다는 부처님", 3.5),
    ("오늘 이 노래가 당신의 소원을\n부처님께 전해주는\n마음의 기도가 되기를 바랍니다", 2.8),
]

# 캡컷의 글자 크기 단위를 픽셀로 바꾸는 배율입니다.
# 이미 렌더해 본 썸네일(font_size 14 x scale 1.171 → 한 글자 약 135px)에서
# 역산했습니다. 눈대중으로 잡지 않습니다.
배율 = 8.21

def _px(size, scale):
    return int(round(size * scale * 배율))

# (글자크기, 중심x, 중심y, 글자색, 테두리두께)  — 캡컷 「황주영상」 값 그대로
자리 = {
    "채널명":  (_px(13, 0.379),  209,  55, "white",   4),
    "안내문구": (_px(7,  1.120), 1010,  99, "#00ff18", 5),
    "하단문구": (_px(9,  1.000),  960, 959, "white",   6),
    "곡제목":  (_px(13, 0.588), 1560, 800, "white",   6),
    "인트로":  (_px(9,  1.381),  960, 590, "white",   8),
}


def 글꼴깔기(임시폴더):
    """필터 경로에 콜론이 있으면 깨지므로 임시 폴더에 짧은 이름으로 둡니다."""
    if not os.path.exists(글꼴):
        return None
    쓸것 = os.path.join(임시폴더, "f.otf")
    if not os.path.exists(쓸것):
        shutil.copy(글꼴, 쓸것)
    return "f.otf"


def 글판(임시폴더, 이름, 글):
    with open(os.path.join(임시폴더, 이름), "w", encoding="utf-8") as f:
        f.write(글)
    return 이름


def _한덩이(글꼴이름, 파일이름, 몫, 켜짐=None):
    크기, cx, cy, 색, 테두리 = 자리[몫]
    # 을지로체는 줄 높이가 커서 그냥 두면 두 줄 사이가 벌어집니다.
    # 캡컷에서 보이는 간격에 맞춰 글자 크기에 비례해 좁힙니다.
    줄간격 = -int(round(크기 * 0.22))
    조각 = ("drawtext=fontfile=%s:textfile=%s:fontcolor=%s:fontsize=%d"
           ":borderw=%d:bordercolor=black@0.9:line_spacing=%d"
           ":x=%d-text_w/2:y=%d-text_h/2"
           % (글꼴이름, 파일이름, 색, 크기, 테두리, 줄간격, cx, cy))
    if 켜짐:
        조각 += ":enable='%s'" % 켜짐
    return 조각


def 고정문구필터(임시폴더, 곡제목):
    """채널명(좌상단) · 안내문구(우상단) · 하단 문구 · 곡 제목(우하단)"""
    글꼴이름 = 글꼴깔기(임시폴더)
    if not 글꼴이름:
        return []
    조각 = [
        _한덩이(글꼴이름, 글판(임시폴더, "t_ch.txt", 채널명), "채널명"),
        _한덩이(글꼴이름, 글판(임시폴더, "t_no.txt", 안내문구), "안내문구"),
        _한덩이(글꼴이름, 글판(임시폴더, "t_bt.txt", 하단문구), "하단문구"),
    ]
    if 곡제목:
        조각.append(_한덩이(글꼴이름, 글판(임시폴더, "t_ti.txt", 곡제목), "곡제목"))
    return 조각


def 인트로필터(임시폴더):
    """맨 앞에 붙일 14초 인트로. 문구가 차례로 바뀝니다."""
    글꼴이름 = 글꼴깔기(임시폴더)
    if not 글꼴이름:
        return [], 0.0
    조각 = 고정문구필터(임시폴더, "")
    시작 = 0.0
    for 번호, (글, 길이) in enumerate(인트로들):
        조각.append(_한덩이(글꼴이름, 글판(임시폴더, "t_in%d.txt" % 번호, 글),
                        "인트로", "between(t,%.2f,%.2f)" % (시작, 시작 + 길이)))
        시작 += 길이
    return 조각, 시작
