def 시각표기(마이크로초):
    전체초 = int(마이크로초 // 1_000_000)
    시, 나머지 = divmod(전체초, 3600)
    분, 초 = divmod(나머지, 60)
    if 시:
        return "%d:%02d:%02d" % (시, 분, 초)
    return "%d:%02d" % (분, 초)


def 길이표기(마이크로초):
    전체분 = int(마이크로초 // 60_000_000)
    시, 분 = divmod(전체분, 60)
    if 시 and 분:
        return "%d시간 %d분" % (시, 분)
    if 시:
        return "%d시간" % 시
    return "%d분" % 분


def 경전표읽기():
    """02-가사 의 md 들에서 (제목 → 경전, 원문) 을 모읍니다."""
    표 = {}
    for 파일 in sorted(가사폴더.glob("*.md")):
        if 파일.stem.startswith("_"):
            continue
        글 = io.open(파일, encoding="utf-8").read()
        경전 = re.search(r"^- \*\*출처 경전\*\*:\s*(.+)$", 글, re.M)
        원문 = re.search(r"^- \*\*인용 원문\*\*:\s*(.+)$", 글, re.M)
        제목 = re.search(r"^## Song Title\s*\n+```\s*\n(.+?)\n```", 글, re.M | re.S)
        이름 = 제목.group(1).strip() if 제목 else re.sub(r"^\d+-", "", 파일.stem)
        표[이름.replace(" ", "")] = {
            "제목": 이름,
            "경전": 경전.group(1).strip() if 경전 else "",
            "원문": 원문.group(1).strip() if 원문 else "",
        }
    return 표


def 곡뽑기(프로젝트=None, 수록곡파일=None):
    """(시작 마이크로초, 곡 제목) 을 순서대로 뽑습니다.

    두 군데서 읽을 수 있습니다.
      · 수록곡.json — `모음집이어붙이기.py` 가 남긴 것 (이쪽이 기본)
      · 캡컷 프로젝트 — 캡컷으로 모음집을 만들었을 때
    """
    if 수록곡파일:
        자료 = json.load(io.open(수록곡파일, encoding="utf-8"))
        곡들 = [(항["시작"], 항["제목"]) for 항 in 자료["곡들"]]
        return 곡들, 자료["전체길이"]

    경로 = 캡컷루트 / 프로젝트 / "draft_content.json"
    if not 경로.exists():
        sys.exit("[실패] 캡컷 프로젝트를 찾을 수 없습니다: " + str(경로))
    d = json.load(io.open(경로, encoding="utf-8"))
    소리 = {m["id"]: m for m in d["materials"]["audios"]}
    트랙 = next(t for t in d["tracks"] if t["type"] == "audio")

    곡들 = []
    for 칸 in sorted(트랙["segments"], key=lambda s: s["target_timerange"]["start"]):
        이름 = 소리[칸["material_id"]]["name"].rsplit(".", 1)[0]
        바탕 = 이름[:이름.rindex(" (")] if 이름.endswith(")") and " (" in 이름 else 이름
        곡들.append((칸["target_timerange"]["start"], 바탕))
    return 곡들, d["duration"]


