def 은는(말):
    """받침이 있으면 「은」, 없으면 「는」. 「불심명언는」 같은 말이 나가면
    글 전체가 대충 쓴 것처럼 보입니다."""
    끝 = 말.strip()[-1]
    if not ("가" <= 끝 <= "힣"):
        return "는"
    return "은" if (ord(끝) - 0xAC00) % 28 else "는"


