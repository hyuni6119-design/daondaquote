    경전표 = 경전표읽기()

    # 수록곡(챕터) — 같은 곡이 여러 번 나와도 처음 한 번만 적습니다.
    # 반복되는 곡까지 다 적으면 챕터 목록이 같은 제목으로 도배되기 때문입니다.
    센것 = {}
    수록곡줄 = []
    for 시작, 제목 in 곡들:
        센것[제목] = 센것.get(제목, 0) + 1
        if 센것[제목] > 1 and not 반복표시:
            continue
        표기 = 제목 if 센것[제목] == 1 else "%s (%d)" % (제목, 센것[제목])
        수록곡줄.append("%s %s" % (시각표기(시작), 표기))

    # 유튜브는 첫 줄이 0:00 이 아니면 챕터를 아예 만들지 않습니다.
    # 앞에 인트로가 붙어 첫 곡이 0:00 이 아니면 인사말 줄을 넣어 줍니다.
    if 곡들 and 곡들[0][0] > 0:
        수록곡줄.insert(0, "0:00 인사말")

    # 출처 경전 — 제목마다 한 번만
    본제목들 = list(dict.fromkeys(제목 for _, 제목 in 곡들))
    출처줄, 경전태그 = [], []
    빠진것 = []
    for 제목 in 본제목들:
        정보 = 경전표.get(제목.replace(" ", ""))
